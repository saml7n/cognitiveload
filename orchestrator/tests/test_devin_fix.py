VALID_CARD = {
    "schema_version": "v1",
    "classification": "bug",
    "confidence": 0.92,
    "summary": "Off-by-one in /summary endpoint.",
    "questions": [],
    "affected_paths": ["demo_app/services/stats_service.py"],
    "suggested_labels": ["bug"],
    "suggested_priority": "medium",
}


def _make_nudge_body(*issue_numbers, ticked=None):
    """Build a realistic PR nudge comment body with checkboxes.

    Args:
        issue_numbers: Issue numbers to include.
        ticked: Set of issue numbers whose checkbox is ticked.
    """
    ticked = ticked or set()
    lines = [
        "## 🔔 PR Nudge — Related Triaged Issues",
        "",
        "This PR touches code linked to the following triaged issues.",
        "",
    ]
    for n in issue_numbers:
        lines.append(f"### #{n}: Bug #{n}")
        lines.append(f"**Classification:** `bug` | **Priority:** `high` | **Confidence:** `0.9`")
        lines.append(f"> Summary for issue #{n}")
        lines.append("")
        lines.append("**Overlapping files:**")
        lines.append(f"- `demo_app/services/stats_service.py`")
        lines.append("")
        state = "x" if n in ticked else " "
        lines.append(f"- [{state}] **Attempt auto-fix for #{n}** with Devin")
        lines.append("")
    lines.append("---")
    lines.append("*Generated by Devin PR Nudge (v1.0)*")
    lines.append("")
    lines.append(PR_NUDGE_MARKER)
    return "\n".join(lines)


def _make_triage_comment(card=None):
    """Build a triage comment with embedded card JSON."""
    card = card or VALID_CARD
    return (
        f"{DEFAULT_MARKER}\n\n## Triage Card\n\n"
        f"<!-- devin-triage:v1\n{json.dumps(card)}\n-->"
    )


