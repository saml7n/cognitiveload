class TestUpdateCommentWithResult(unittest.TestCase):

    def test_appends_result_section(self):
        gh = MagicMock()
        body = _make_comment_body()
        result = "\n\n### ✅ Auto-fix attempted\nPR link here."

        _update_comment_with_result(gh, "owner/repo", 1, body, result)

        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("✅ Auto-fix attempted", updated)
        self.assertIn("PR link here.", updated)

    def test_replaces_previous_result_section(self):
        gh = MagicMock()
        body = _make_comment_body() + "\n\n### ❌ Auto-fix failed\nOld failure text."
        result = "\n\n### ✅ Auto-fix attempted\nNew PR link."

        _update_comment_with_result(gh, "owner/repo", 1, body, result)

        updated = gh.upsert_comment.call_args[0][3]
        self.assertNotIn("❌ Auto-fix failed", updated)
        self.assertIn("✅ Auto-fix attempted", updated)


