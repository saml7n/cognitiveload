class TestExtractCard(unittest.TestCase):

    def test_extracts_valid_card(self):
        body = _make_comment_body()
        card = extract_card_from_comment(body)
        self.assertIsNotNone(card)
        self.assertEqual(card["classification"], "bug")

    def test_returns_none_without_marker(self):
        self.assertIsNone(extract_card_from_comment("No card here."))

    def test_returns_none_for_corrupt_json(self):
        body = "<!-- devin-triage:v1\n{not json}\n-->"
        self.assertIsNone(extract_card_from_comment(body))


