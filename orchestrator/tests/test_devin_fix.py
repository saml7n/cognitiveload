class TestUpdateNudgeComment(unittest.TestCase):

    def test_appends_result_section(self):
        gh = MagicMock()
        body = _make_nudge_body(2, ticked={2})
        result = "\n\n### ✅ Auto-fix for #2\nPR link here."

        _update_nudge_comment_with_result(gh, "owner/repo", 10, body, 2, result)

        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("✅ Auto-fix for #2", updated)
        self.assertIn("PR link here.", updated)

    def test_replaces_previous_result_for_same_issue(self):
        gh = MagicMock()
        body = _make_nudge_body(2, ticked={2}) + "\n\n### ❌ Auto-fix failed for #2\nOld failure text."
        result = "\n\n### ✅ Auto-fix for #2\nNew PR link."

        _update_nudge_comment_with_result(gh, "owner/repo", 10, body, 2, result)

        updated = gh.upsert_comment.call_args[0][3]
        self.assertNotIn("❌ Auto-fix failed for #2", updated)
        self.assertIn("✅ Auto-fix for #2", updated)


