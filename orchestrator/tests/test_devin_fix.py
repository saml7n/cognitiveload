class TestAttemptFix(unittest.TestCase):

    def _mock_pr_response(self, pr_url=None):
        resp = MagicMock()
        resp.raise_for_status.return_value = None
        if pr_url:
            resp.json.return_value = [{"html_url": pr_url}]
        else:
            resp.json.return_value = []
        return resp

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_success_flow_posts_pr_link(self, MockDevin, MockGH):
        devin = MockDevin.return_value
        devin.create_session.return_value = "sess-fix-1"
        devin.poll_session.return_value = {
            "status_enum": "finished",
            "messages": [],
        }

        gh = MockGH.return_value
        # _find_fix_pr uses gh._session.get
        gh._session.get.return_value = self._mock_pr_response(
            "https://github.com/owner/repo/pull/42"
        )
        gh.base_url = "https://api.github.com"

        comment_body = _make_comment_body(checked=True)

        attempt_fix(
            repo="owner/repo",
            issue_number=2,
            issue_title="Off-by-one",
            issue_body="Count is wrong.",
            comment_body=comment_body,
        )

        # Verify comment was updated with success
        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("✅ Auto-fix attempted", updated)
        self.assertIn("pull/42", updated)

        # Verify fix-attempted label
        gh.add_labels.assert_called_once()
        labels = gh.add_labels.call_args[0][2]
        self.assertIn(LABEL_FIX_ATTEMPTED, labels)

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_failure_flow_posts_pointers(self, MockDevin, MockGH):
        devin = MockDevin.return_value
        devin.create_session.return_value = "sess-fix-2"
        devin.poll_session.return_value = {
            "status_enum": "finished",
            "messages": [
                {"type": "devin_message", "message": "I could not reproduce the bug after multiple attempts."},
            ],
        }

        gh = MockGH.return_value
        # No PR found
        gh._session.get.return_value = self._mock_pr_response(None)
        gh.base_url = "https://api.github.com"

        comment_body = _make_comment_body(checked=True)

        attempt_fix(
            repo="owner/repo",
            issue_number=2,
            issue_title="Off-by-one",
            issue_body="Count is wrong.",
            comment_body=comment_body,
        )

        # Verify comment was updated with failure
        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("❌ Auto-fix failed", updated)

        # Verify fix-failed label
        gh.add_labels.assert_called_once()
        labels = gh.add_labels.call_args[0][2]
        self.assertIn(LABEL_FIX_FAILED, labels)

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_aborts_when_no_triage_card(self, MockDevin, MockGH):
        """If the comment has no embedded triage card, do nothing."""
        attempt_fix(
            repo="owner/repo",
            issue_number=2,
            issue_title="Test",
            issue_body="Test body.",
            comment_body="Just a plain comment with no card.",
        )

        # Devin should never be called
        MockDevin.return_value.create_session.assert_not_called()


