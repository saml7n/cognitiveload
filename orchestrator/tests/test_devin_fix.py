# detect_ticked_issues
# ---------------------------------------------------------------------------


class TestDetectTickedIssues(unittest.TestCase):

    def test_single_checkbox_ticked(self):
        old = _make_nudge_body(2, 3, ticked=set())
        new = _make_nudge_body(2, 3, ticked={2})
        self.assertEqual(detect_ticked_issues(old, new), [2])

    def test_multiple_checkboxes_ticked(self):
        old = _make_nudge_body(2, 3, ticked=set())
        new = _make_nudge_body(2, 3, ticked={2, 3})
        self.assertEqual(detect_ticked_issues(old, new), [2, 3])

    def test_already_ticked_no_change(self):
        old = _make_nudge_body(2, 3, ticked={2})
        new = _make_nudge_body(2, 3, ticked={2})
        self.assertEqual(detect_ticked_issues(old, new), [])

    def test_none_ticked(self):
        old = _make_nudge_body(2, 3, ticked=set())
        new = _make_nudge_body(2, 3, ticked=set())
        self.assertEqual(detect_ticked_issues(old, new), [])

    def test_no_checkboxes_at_all(self):
        old = "Just a normal comment."
        new = "Just a normal comment, edited."
        self.assertEqual(detect_ticked_issues(old, new), [])

    def test_one_already_ticked_another_newly_ticked(self):
        old = _make_nudge_body(2, 3, ticked={2})
        new = _make_nudge_body(2, 3, ticked={2, 3})
        self.assertEqual(detect_ticked_issues(old, new), [3])


