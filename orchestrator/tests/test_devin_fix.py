class TestAttemptFix(unittest.TestCase):
    """Full flow with mocked Devin and GitHub clients (PR nudge context)."""

    def _mock_pr_response(self, pr_url=None):
        resp = MagicMock()
        resp.raise_for_status.return_value = None
        if pr_url:
            resp.json.return_value = [{"html_url": pr_url}]
        else:
            resp.json.return_value = []
        return resp

    def _mock_issue_response(self, title="Off-by-one", body="Count is wrong."):
        resp = MagicMock()
        resp.raise_for_status.return_value = None
        resp.json.return_value = {"title": title, "body": body}
        return resp

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_success_flow_posts_pr_link_on_nudge(self, MockDevin, MockGH):
        devin = MockDevin.return_value
        devin.create_session.return_value = "sess-fix-1"
        devin.poll_session.return_value = {
            "status_enum": "finished",
            "messages": [],
        }

        gh = MockGH.return_value
        gh.base_url = "https://api.github.com"

        # fetch_triage_card returns VALID_CARD from issue #2's comments
        gh.get_issue_comments.return_value = [
            {"body": _make_triage_comment(VALID_CARD)},
        ]
        # Fetch issue details + find fix PR
        gh._session.get.side_effect = [
            self._mock_issue_response(),
            self._mock_pr_response("https://github.com/owner/repo/pull/42"),
        ]

        comment_body = _make_nudge_body(2, ticked={2})

        attempt_fix(
            repo="owner/repo",
            pr_number=10,
            issue_number=2,
            comment_body=comment_body,
        )

        # Verify nudge comment was updated with success
        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("✅ Auto-fix for #2", updated)
        self.assertIn("pull/42", updated)

        # Verify fix-attempted label on the issue
        gh.add_labels.assert_called_once()
        labels = gh.add_labels.call_args[0][2]
        self.assertIn(LABEL_FIX_ATTEMPTED, labels)

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_failure_flow_posts_pointers_on_nudge(self, MockDevin, MockGH):
        devin = MockDevin.return_value
        devin.create_session.return_value = "sess-fix-2"
        devin.poll_session.return_value = {
            "status_enum": "finished",
            "messages": [
                {"type": "devin_message", "message": "I could not reproduce the bug after multiple attempts."},
            ],
        }

        gh = MockGH.return_value
        gh.base_url = "https://api.github.com"

        gh.get_issue_comments.return_value = [
            {"body": _make_triage_comment(VALID_CARD)},
        ]
        gh._session.get.side_effect = [
            self._mock_issue_response(),
            self._mock_pr_response(None),  # No PR found
        ]

        comment_body = _make_nudge_body(2, ticked={2})

        attempt_fix(
            repo="owner/repo",
            pr_number=10,
            issue_number=2,
            comment_body=comment_body,
        )

        # Verify nudge comment was updated with failure
        gh.upsert_comment.assert_called_once()
        updated = gh.upsert_comment.call_args[0][3]
        self.assertIn("❌ Auto-fix failed for #2", updated)

        # Verify fix-failed label on the issue
        gh.add_labels.assert_called_once()
        labels = gh.add_labels.call_args[0][2]
        self.assertIn(LABEL_FIX_FAILED, labels)

    @patch("orchestrator.devin_fix.GitHubClient")
    @patch("orchestrator.devin_fix.DevinClient")
    def test_aborts_when_no_triage_card_on_issue(self, MockDevin, MockGH):
        """If the issue has no triage card, do nothing."""
        gh = MockGH.return_value
        gh.get_issue_comments.return_value = [
            {"body": "Regular human comment, no card."},
        ]

        attempt_fix(
            repo="owner/repo",
            pr_number=10,
            issue_number=2,
            comment_body=_make_nudge_body(2, ticked={2}),
        )

        # Devin should never be called
        MockDevin.return_value.create_session.assert_not_called()


