VALID_CARD = {
    "schema_version": "v1",
    "classification": "bug",
    "confidence": 0.92,
    "summary": "Off-by-one in /summary endpoint.",
    "questions": [],
    "affected_paths": ["demo_app/services/stats_service.py"],
    "suggested_labels": ["bug"],
    "suggested_priority": "medium",
}


def _make_comment_body(card=None, checked=False):
    """Build a realistic triage comment body."""
    card = card or VALID_CARD
    checkbox = "- [x] Attempt auto-fix with Devin" if checked else "- [ ] Attempt auto-fix with Devin"
    return (
        "## 🤖 Devin Triage Intelligence\n\n"
        f"**Summary:** {card['summary']}\n\n"
        "### 🔧 Auto-fix\n"
        f"{checkbox}\n\n"
        "---\n"
        "*Generated by Devin (v1.0)*\n\n"
        f"<!-- devin-triage:v1\n{json.dumps(card)}\n-->"
    )


# ---------------------------------------------------------------------------
# checkbox_was_ticked
# ---------------------------------------------------------------------------


class TestCheckboxDetection(unittest.TestCase):

    def test_unchecked_to_checked(self):
        old = _make_comment_body(checked=False)
        new = _make_comment_body(checked=True)
        self.assertTrue(checkbox_was_ticked(old, new))

    def test_already_checked_no_change(self):
        old = _make_comment_body(checked=True)
        new = _make_comment_body(checked=True)
        self.assertFalse(checkbox_was_ticked(old, new))

    def test_unchecked_stays_unchecked(self):
        old = _make_comment_body(checked=False)
        new = _make_comment_body(checked=False)
        self.assertFalse(checkbox_was_ticked(old, new))

    def test_no_checkbox_at_all(self):
        old = "Just a normal comment."
        new = "Just a normal comment, edited."
        self.assertFalse(checkbox_was_ticked(old, new))


